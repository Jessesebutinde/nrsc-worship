const BY_ID = new Map(PRESETS.map((p) => [p.id, p]));
export const presetById = (id) => BY_ID.get(id) || null;

/** Sampled banks a preset needs before it can sound. */
export function presetBanks(preset) {
  const prog = preset && preset.prog;
  if (!prog) return [];
  const list = prog.type === 'layer' ? prog.layers : [prog];
  return list.filter((p) => p.type === 'sampler' && p.bank).map((p) => p.bank);
}

export function searchPresets(query, family, extra = []) {
  const all = [...PRESETS, ...extra];
  const q = (query || '').trim().toLowerCase();
  return all.filter((p) => (!family || p.family === family) && (!q || `${p.name} ${p.desc} ${(p.tags || []).join(' ')} ${p.kind}`.toLowerCase().includes(q)));
}
