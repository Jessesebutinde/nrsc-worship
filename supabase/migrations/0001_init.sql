-- NRSC Worship — song database and set lists.
-- Run once in Supabase: SQL Editor → paste this whole file → Run. Safe to run again.
--
-- The app never talks to these tables from the browser. The Vercel /api functions
-- call the functions below with the service key, so every save is one atomic step
-- (a song and its themes, a set list and its songs) and the tables stay private.

create extension if not exists pg_trgm;

-- ------------------------------------------------------------------ tables

create table if not exists public.themes (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 60),
  description text,
  created_at timestamptz not null default now()
);
create unique index if not exists themes_name_key on public.themes (lower(name));

create table if not exists public.songs (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 1 and 200),
  title_alt text,
  language text not null default 'luganda' check (language in ('luganda', 'english', 'both')),
  lyrics_luganda text,
  lyrics_english text,
  session text not null default 'praise' check (session in ('praise', 'worship')),
  song_key text,
  tempo_bpm integer check (tempo_bpm is null or tempo_bpm between 30 and 260),
  youtube_url text check (youtube_url is null or youtube_url ~* '^https?://'),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists songs_title_idx on public.songs (lower(title));
create index if not exists songs_search_idx on public.songs using gin (
  (coalesce(title, '') || ' ' || coalesce(title_alt, '') || ' ' || coalesce(lyrics_luganda, '') || ' ' || coalesce(lyrics_english, '')) gin_trgm_ops
);

create table if not exists public.song_themes (
  song_id bigint not null references public.songs (id) on delete cascade,
  theme_id bigint not null references public.themes (id) on delete cascade,
  primary key (song_id, theme_id)
);
create index if not exists song_themes_theme_idx on public.song_themes (theme_id);

create table if not exists public.set_lists (
  id bigint generated by default as identity primary key,
  service_date date not null,
  theme_id bigint references public.themes (id) on delete set null,
  title text,
  leader_name text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists set_lists_date_idx on public.set_lists (service_date desc);

create table if not exists public.set_list_songs (
  id bigint generated by default as identity primary key,
  set_list_id bigint not null references public.set_lists (id) on delete cascade,
  song_id bigint not null references public.songs (id) on delete cascade,
  section text not null check (section in ('praise', 'worship')),
  position integer not null check (position >= 1)
);
create index if not exists set_list_songs_set_idx on public.set_list_songs (set_list_id, section, position);
create index if not exists set_list_songs_song_idx on public.set_list_songs (song_id);

-- Private: only the service key (used by the /api functions) can read or write.
alter table public.themes enable row level security;
alter table public.songs enable row level security;
alter table public.song_themes enable row level security;
alter table public.set_lists enable row level security;
alter table public.set_list_songs enable row level security;

